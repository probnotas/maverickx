"""Trace the monitor's glass in the desk image and write src/screenShape.ts.

Run after replacing the desk image (needs ffmpeg):
    python3 scripts/trace-screen.py public/img/desk/desk-2560.jpg

The glass is found as the blue-lit area around the image centre. The result is
the screen's bounding box (fractions of the image) and a clip-path polygon
(percent of that box) that matches its curved CRT outline.
"""
import json, subprocess, sys

src = sys.argv[1] if len(sys.argv) > 1 else "public/img/desk/desk-2560.jpg"
probe = subprocess.run(
    ["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height", "-of", "json", src],
    capture_output=True, check=True, text=True,
)
W, H = (json.loads(probe.stdout)["streams"][0][k] for k in ("width", "height"))
raw = subprocess.run(
    ["ffmpeg", "-v", "error", "-i", src, "-f", "rawvideo", "-pix_fmt", "rgb24", "-"], capture_output=True, check=True
).stdout


def lit(x, y):
    i = (y * W + x) * 3
    r, g, b = raw[i], raw[i + 1], raw[i + 2]
    return b > r + 12 and b > 32 and r < 80


cx = W // 2
ys = [y for y in range(int(H * 0.25), int(H * 0.72)) if lit(cx, y)]
y0, y1 = min(ys), max(ys)


def walk(y, step):
    x, miss, last = cx, 0, cx
    while 0 < x < W - 1 and miss < 6:
        x += step
        if lit(x, y):
            last, miss = x, 0
        else:
            miss += 1
    return last


pad = max(3, W // 600)  # grow slightly so no blue rim survives at the edge
step = max(1, H // 300)
raw_rows = [(y, walk(y, -1), walk(y, 1)) for y in range(y0, y1 + 1, step)]
# Smooth out jaggies: each row takes the widest extent of its neighbours.
k = 3
rows = []
for i, (y, _, _) in enumerate(raw_rows):
    near = raw_rows[max(0, i - k) : i + k + 1]
    rows.append((y, min(a for _, a, _ in near) - pad, max(b for _, _, b in near) + pad))
rows[0] = (y0 - pad, rows[0][1], rows[0][2])
rows[-1] = (y1 + pad, rows[-1][1], rows[-1][2])
bx0, bx1 = min(r[1] for r in rows), max(r[2] for r in rows)
by0, by1 = rows[0][0], rows[-1][0]
bw, bh = bx1 - bx0, by1 - by0

pct = lambda x, y: f"{(x - bx0) / bw * 100:.2f}% {(y - by0) / bh * 100:.2f}%"
pts = [pct(a, y) for y, a, _ in rows] + [pct(b, y) for y, _, b in reversed(rows)]
box = {"left": bx0 / W, "top": by0 / H, "width": bw / W, "height": bh / H}

out = f"""// Generated by scripts/trace-screen.py from {src}. Do not edit by hand.
export const screenBox = {json.dumps({k: round(v, 5) for k, v in box.items()})};
export const screenClip = "polygon({', '.join(pts)})";
"""
open("src/screenShape.ts", "w").write(out)
print("screen box", {k: round(v, 4) for k, v in box.items()}, "points", len(pts))
